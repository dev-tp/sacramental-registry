CREATE TABLE registry (
  id INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
  first_name VARCHAR(32),
  last_name VARCHAR(32),
  sex ENUM('M', 'F'),
  birthdate DATE,
  birth_city VARCHAR(32),
  home_address_line_1 VARCHAR(32),
  home_address_line_2 VARCHAR(16),
  city VARCHAR(32),
  region VARCHAR(4),
  zip_code VARCHAR(16),
  father VARCHAR(64),
  mother VARCHAR(64),
  baptism_date DATE,
  baptism_church VARCHAR(32),
  baptism_godfather VARCHAR(32),
  baptims_proxy_godfather VARCHAR(32),
  baptism_godmother VARCHAR(32),
  baptism_proxy_godmother VARCHAR(32),
  baptism_presider VARCHAR(32),
  baptism_volume VARCHAR(4),
  baptism_page VARCHAR(4),
  baptism_number VARCHAR(6),
  communion_date DATE,
  communion_church VARCHAR(32),
  communion_presider VARCHAR(32),
  communion_volume VARCHAR(4),
  communion_page VARCHAR(4),
  communion_number VARCHAR(6),
  confirmation_date DATE,
  confirmation_church VARCHAR(32),
  confirmation_presider VARCHAR(32),
  confirmation_name VARCHAR(32),
  confirmation_sponsor VARCHAR(32),
  confirmation_volume VARCHAR(4),
  confirmation_page VARCHAR(4),
  confirmation_number VARCHAR(6),
  marriage_date DATE,
  marriage_partner_first_name VARCHAR(32),
  marriage_partner_last_name VARCHAR(32),
  marriage_partner_father VARCHAR(64),
  marriage_partner_mother VARCHAR(64),
  marriage_partner_home_address_line_1 VARCHAR(32),
  marriage_partner_home_address_line_2 VARCHAR(16),
  marriage_partner_city VARCHAR(32),
  marriage_partner_baptism_date DATE,
  marriage_partner_baptism_church VARCHAR(32),
  marriage_wedding_place VARCHAR(32),
  marriage_presider VARCHAR(32),
  marriage_witness_1 VARCHAR(32),
  marriage_witness_2 VARCHAR(32),
  marriage_volume VARCHAR(4),
  marriage_page VARCHAR(4),
  marriage_number VARCHAR(6),
  death_date DATE,
  death_burial_date DATE,
  death_burial VARCHAR(32),
  death_anointing VARCHAR(32),
  death_presider VARCHAR(32),
  death_volume VARCHAR(4),
  death_page VARCHAR(4),
  death_number VARCHAR(6),
  comments TEXT,
  date_entered DATETIME DEFAULT current_timestamp()
) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
